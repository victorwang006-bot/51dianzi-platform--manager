export const CHAT_STICKERS = [
  ...NOTO_CHAT_STICKERS,
  ...EMOJI_CHAT_STICKERS,
  ...YAYATUAN_CHAT_STICKERS,
  ...BUSINESS_CHAT_STICKERS,
] as const;
export type ChatStickerId = (typeof CHAT_STICKERS)[number]["id"];
const RECENT_CHAT_STICKERS_STORAGE_KEY = "51-chat-recent-stickers-v1";

export function getChatSticker(stickerId: string) {
  return CHAT_STICKERS.find(sticker => sticker.id === stickerId) ?? null;
}

export function getRecentChatStickerIds(limit = 8): ChatStickerId[] {
  if (typeof window === "undefined") return [];
  try {
    const parsed = JSON.parse(window.localStorage.getItem(RECENT_CHAT_STICKERS_STORAGE_KEY) || "[]");
    if (!Array.isArray(parsed)) return [];
    const knownIds = new Set<ChatStickerId>(CHAT_STICKERS.map(sticker => sticker.id));
    return Array.from(new Set(parsed.filter((id): id is ChatStickerId => knownIds.has(id)))).slice(0, limit);
  } catch {
    return [];
  }
}

export function recordRecentChatSticker(stickerId: ChatStickerId, limit = 8): ChatStickerId[] {
  const next = [
    stickerId,
    ...getRecentChatStickerIds(limit).filter(id => id !== stickerId),
  ].slice(0, limit);
  if (typeof window !== "undefined") {
    try {
      window.localStorage.setItem(RECENT_CHAT_STICKERS_STORAGE_KEY, JSON.stringify(next));
    } catch {
      // 受限浏览器可能禁止localStorage；表情发送本身不受影响。
    }
  }
  return next;
}
