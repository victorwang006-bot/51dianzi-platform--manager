import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {nullablePageReceiver,H,parse,specs,resolve} from '../admin-new-information-v1/build-page-markers.mjs';
const W=process.argv[2];assert(W&&path.isAbsolute(W),'Absolute output directory required');
const A='/home/ubuntu/work/customer-runtime-audit-20261122-1137';
const evidence=JSON.parse(fs.readFileSync(A+'/orders/actual-import-resolution.json','utf8'));
const oldURL=evidence.resolutions[0].resolvedOnce;
const oldFile=A+'/orders/'+path.basename(oldURL);
const before=fs.readFileSync(oldFile,'utf8');
assert.equal(H(before),'e30f28c6506b3062865c507c1b42999ea5d2c99830f40d14b388d11998e68eed');
const token='const __niPageRows=(o.data.rows??[])';
