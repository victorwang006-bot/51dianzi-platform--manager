newMap.scopes[record.longestApplicableScope][record.normalizedKey]=newURL;
if(inherited)newMap.scopes[newURL]=structuredClone(oldMap.scopes[inherited]);
assert.equal(resolve(record.actualSpecifier,evidence.entry,newMap),newURL);
assert.deepEqual(specs(after),specs(before));
const dependencies=specs(before).map(spec=>({specifier:spec,before:resolve(spec,oldURL,oldMap),after:resolve(spec,newURL,newMap)}));
for(const dep of dependencies)assert.equal(dep.before,dep.after,dep.specifier);
