const after=before.replace(token,replacement);
assert.equal(after.replace(replacement,token),before);
assert.equal(Buffer.byteLength(after),Buffer.byteLength(before)+1);
parse(after);
const newHash=H(after),newName='Orders-new-information-'+newHash.slice(0,16)+'.js';
const newURL=path.posix.dirname(oldURL)+'/'+newName;
const local=W+'/'+newName;
assert.notEqual(newURL,oldURL);
const html=fs.readFileSync(A+'/public-current-index.html','utf8');
assert.equal(H(html),evidence.htmlSHA);
const maps=[...html.matchAll(/<script[^>]*type="importmap"[^>]*>([\s\S]*?)<\/script>/g)];
assert.equal(maps.length,1);
const oldMap=JSON.parse(maps[0][1]);
const record=evidence.resolutions[0];
assert.equal(resolve(record.actualSpecifier,evidence.entry,oldMap),oldURL);
const inherited=Object.keys(oldMap.scopes??{}).filter(s=>oldURL.startsWith(s)).sort((a,b)=>b.length-a.length)[0];
