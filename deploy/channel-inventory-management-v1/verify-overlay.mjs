#!/usr/bin/env node
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import ts from 'typescript';
const workspace = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const out = path.join(workspace, 'overlay-build');
const manifest = JSON.parse(await fs.readFile(path.join(out, 'manifest.json'), 'utf8'));
const sha = x => crypto.createHash('sha256').update(x).digest('hex');
for (const [name, entry] of Object.entries(manifest.baseline)) assert.equal(sha(await fs.readFile(entry.path)), entry.sha256, `baseline drift: ${name}`);
for (const [name, entry] of Object.entries(manifest.outputs)) assert.equal(sha(await fs.readFile(entry.path)), entry.sha256, `candidate hash mismatch: ${name}`);
const oldChunk = await fs.readFile(manifest.baseline.chunk.path, 'utf8');
const newChunk = await fs.readFile(manifest.outputs.js.path, 'utf8');
const [oldStart, oldEnd] = manifest.onlyChangedFunction.oldRange;
const [newStart, newEnd] = manifest.onlyChangedFunction.replacementRange;
assert.equal(oldStart, newStart);
assert.ok(Buffer.from(newChunk.slice(0, newStart) + oldChunk.slice(oldStart, oldEnd) + newChunk.slice(newEnd)).equals(Buffer.from(oldChunk)), 'only-function byte preservation failed');
const parsed = ts.createSourceFile('candidate.js', newChunk, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
assert.equal(parsed.parseDiagnostics.length, 0);
assert.equal(parsed.statements.filter(n => ts.isFunctionDeclaration(n) && n.name?.text === 'r1').length, 1);
const oldHtml = await fs.readFile(manifest.baseline.html.path, 'utf8');
const newHtml = await fs.readFile(manifest.outputs.html.path, 'utf8');
const htmlAdditions = [...newHtml.matchAll(/<!-- ci-management-v1:start -->[\s\S]*?<!-- ci-management-v1:end -->\n/g)];
assert.equal(htmlAdditions.length, 1);
assert.ok(Buffer.from(newHtml.replace(htmlAdditions[0][0], '')).equals(Buffer.from(oldHtml)), 'HTML/runtime preservation failed');
for (const source of manifest.sources) assert.equal(sha(await fs.readFile(source.path)), source.sha256, `source changed after build; re-run: ${source.path}`);
assert.equal(sha(await fs.readFile(manifest.css.source)), manifest.outputs.css.sha256, 'management CSS changed after build; re-run');
assert.ok(manifest.smoke.passed);
console.log(JSON.stringify({ passed: true, currentSourceHashesMatch: true, chunkPreservedBytes: true, htmlPreservedBytes: true, js: manifest.outputs.js.path, css: manifest.outputs.css.path }, null, 2));
